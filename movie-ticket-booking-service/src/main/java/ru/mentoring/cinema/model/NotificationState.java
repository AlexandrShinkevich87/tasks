package ru.mentoring.cinema.model;

/**
 * Состояние зарегистрированного уведомления о покупке.
 */
public enum NotificationState {
    /** Уведомление ожидает свободного отправщика. */
    PENDING,
    /** Уведомление закреплено за одной попыткой обработки. */
    IN_FLIGHT,
    /** Отправщик подтвердил успешную доставку. */
    SENT,
    /** Попытки исчерпаны; задание сохранено для разбора и ручного повтора. */
    FAILED
}
